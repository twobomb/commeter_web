<?php

namespace app\models;

use Yii;
use yii\web\ForbiddenHttpException;

/**
 * This is the model class for table "repairs".
 *
 * @property string $id
 * @property string|null $date_change
 * @property int $item_id
 * @property float|null $sum
 * @property string $date
 * @property string|null $description
 * @property string $type
 *
 * @property Item $item
 */
class Repair extends \yii\db\ActiveRecord
{
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'repairs';
    }

    public function beforeSave($insert){
        if(!$this->item->department->canAccess())
            throw new ForbiddenHttpException("Вам запрещен доступ к средству подразделния '{$this->item->department->name}'!");

        $this->date_change = nowdate();
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    public static function getTypes(){
        return ["fill"=>"Заправка картриджа","fix"=>"Ремонт","other"=>"Другое"];
    }
    public function DisplayTypeName(){
        if($this->type == null)
            return null;
        $types = self::getTypes();
        if(isset($types[$this->type]))
            return $types[$this->type];
        return $this->type;
    }
    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [[ 'item_id', 'date', 'type'], 'required'],
            [['date_change', 'date'], 'safe'],
            [['item_id'], 'integer'],
            [['sum'], 'number'],
            [['description'], 'string'],
            [['type'], 'string', 'max' => 255],
            [['id'], 'unique'],
            [['item_id'], 'exist', 'skipOnError' => true, 'targetClass' => Item::class, 'targetAttribute' => ['item_id' => 'id']],
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'date_change' => 'Дата изменения',
            'item_id' => 'Средство',
            'sum' => 'Сумма',
            'date' => 'Дата обслуживания',
            'description' => 'Дополнительная информация',
            'type' => 'Тип обслуживания',
        ];
    }

    /**
     * Gets query for [[Item]].
     *
     * @return \yii\db\ActiveQuery
     */
    public function getItem()
    {
        return $this->hasOne(Item::class, ['id' => 'item_id']);
    }
}
